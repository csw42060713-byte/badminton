var PUSH_TABS = ['log', 'matching', 'community', 'coach', 'my'];

/* 푸시 페이로드 → 알림 글·갈 곳. JSON이 아니면 본문 글자만 씁니다. */
function pushPayload(data) {
  var out = { title: '셔틀릭스', body: '', url: './', tag: '' };
  try {
    if (data && typeof data === 'object') {
      out.title = String(data.title || data.heading || out.title).slice(0, 80);
      out.body = String(data.body || data.message || data.text || '').slice(0, 180);
      out.tag = String(data.tag || data.topic || '').slice(0, 64);
      out.url = pushTargetUrl(data.url || data.link || data.click_action || '');
    } else if (data != null) {
      out.body = String(data).slice(0, 180);
    }
  } catch (e) { /* 깨진 페이로드는 기본 알림으로 */ }
  return out;
}

/* 알림 링크는 앱 안 화면으로만 — 다른 주소가 오면 첫 화면으로
 * bm-v1.77.0 — 'chat/<방>' 처럼 뒤에 방 ID가 붙으면 그 방까지 살려 둡니다
 *              ('#/chat' 만 오면 예전처럼 매칭 탭) */
function pushTargetUrl(raw) {
  var s = String(raw || '').trim();
  var i = s.indexOf('#');
  if (i >= 0) s = s.slice(i + 1);
  s = s.replace(/^\/+/, '');
  var parts = s.split(/[\/?#&]+/).filter(Boolean);
  var seg = String(parts[0] || '').toLowerCase();
  if (seg === 'chat') {
    var room = String(parts[1] || '').replace(/[^A-Za-z0-9_-]/g, '').slice(0, 40);
    return room ? './#/chat/' + room : './#/matching';
  }
  if (PUSH_TABS.indexOf(seg) >= 0) return './#/' + seg;
  return './';
}

self.addEventListener('push', function (event) {
  var data = null;
  try { data = event.data ? event.data.json() : null; } catch (e) {
    try { data = event.data ? event.data.text() : null; } catch (e2) { data = null; }
  }
  var msg = pushPayload(data);
  event.waitUntil(
    self.registration.showNotification(msg.title, {
      body: msg.body,
      icon: 'icons/icon-192.png',
      badge: 'icons/icon-192.png',
      tag: msg.tag || 'bm-push',
      renotify: !!msg.tag,
      data: { url: msg.url },
      timestamp: Date.now()
    }).catch(function () { /* 알림을 못 띄워도 서비스워커는 살아 있음 */ })
  );
});

self.addEventListener('notificationclick', function (event) {
  var data = event.notification && event.notification.data ? event.notification.data : {};
  var target = pushTargetUrl(data.url || '');
  event.notification.close();
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then(function (list) {
      for (var i = 0; i < list.length; i++) {
        var c = list[i];
        if (c && typeof c.focus === 'function') {
          return c.focus().then(function () {
            /* 앱이 이미 열려 있으면 탭 이동 메시지로 — 화면을 다시 띄우지 않습니다 */
            try { c.postMessage({ type: 'BM_PUSH_OPEN', url: target }); } catch (e) { /* 무시 */ }
            return c;
          });
        }
      }
      if (self.clients.openWindow) return self.clients.openWindow(target);
    }).catch(function () { /* 무시 */ })
  );
});

/* styles.css?v=… 처럼 물음표가 붙은 요청은 파일 이름으로 한 번 더 찾습니다 */
function bareUrl(url) {
  return String(url || '').split('?')[0].split('#')[0];
}

function matchCached(req) {
  return caches.match(req).then(function (hit) {
    if (hit) return hit;
    return caches.match(bareUrl(req.url));
  });
}

function putCached(req, res) {
  if (!res || !res.ok || res.redirected || res.status !== 200) return;
  var key = bareUrl(req.url);
  var copy = res.clone();
  caches.open(VERSION).then(function (cache) {
    return cache.put(key, copy);
  }).catch(function () {});
}

/* 네트워크 우선 → 실패하면 캐시 (오프라인)
 * 브라우저 HTTP 캐시에 옛 파일이 남아 있어도 서버에 다시 확인합니다(cache: no-cache).
 * (GitHub Pages는 파일에 max-age를 붙여 보내므로 이 확인이 있어야 새 버전이 바로 보입니다.) */
function netFetch(req) {
  try {
    return fetch(req, { cache: 'no-cache' });
  } catch (e) {
    return fetch(req);
  }
}

function networkFirst(req) {
  return netFetch(req).then(function (res) {
    putCached(req, res);
    return res;
  }).catch(function () {
    return matchCached(req).then(function (hit) {
      if (hit) return hit;
      if (req.mode === 'navigate') return caches.match('./index.html');
      return caches.match(bareUrl(new URL('./index.html', self.location).href));
    }).then(function (res) {
      if (res) return res;
      return Response.error();
    });
  });
}

/* 캐시 우선 → 뒤에서 조용히 갱신 */
function cacheFirst(req) {
  return matchCached(req).then(function (hit) {
    if (hit) {
      fetch(req).then(function (res) { putCached(req, res); }).catch(function () {});
      return hit;
    }
    return networkFirst(req);
  });
}

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;
  var url;
  try { url = new URL(req.url); } catch (e) { return; }
  if (url.origin !== self.location.origin) return;

  var dest = req.destination || '';
  var isAppShell = req.mode === 'navigate' || dest === 'document' ||
    dest === 'script' || dest === 'style' || dest === 'worker';

  event.respondWith(isAppShell ? networkFirst(req) : cacheFirst(req));
});
